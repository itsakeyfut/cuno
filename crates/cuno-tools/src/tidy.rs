    /// clang-tidy's own rule: the last glob that matches decides.
    fn last_match(globs: &[String], check: &str) -> bool {
        let mut on = false;
        for glob in globs {
            let (negated, pattern) = match glob.strip_prefix('-') {
                Some(rest) => (true, rest),
                None => (false, glob.as_str()),
            };
            let matches = match pattern.strip_suffix('*') {
                Some(prefix) => check.starts_with(prefix),
                None => check == pattern,
            };
            if matches {
                on = !negated;
            }
        }
        on
    }

    /// Whether `check` runs, and whether it is an error.
    fn judge(config: &TidyConfig, check: &str) -> (bool, bool) {
        let on = last_match(&config.checks, check);
        (on, on && last_match(&config.warnings_as_errors, check))
    }

